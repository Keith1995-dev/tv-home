#!/usr/bin/env python3
"""
Regenerates the launcher's background lists:

  launcher/res/values/aerials.xml  Apple TV aerials (landscapes, cities, space, underwater)
  launcher/res/values/stills.xml   paintings (Art Institute of Chicago, public domain), Google Earth View
                                   satellite photos, and Hubble / Webb images from NASA's image library

Only links and captions go into the app; the TV downloads the pictures itself and keeps a few on disk.
Fetches with curl so the Mac's own certificate store is used.

  python3 tools/gen-backgrounds.py
"""
import concurrent.futures
import io
import json
import os
import subprocess
import tarfile
import urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VALUES = os.path.join(ROOT, 'launcher', 'res', 'values')


def fetch(url, data=None, headers=(), timeout=90):
    cmd = ['curl', '-sfL', '--max-time', str(timeout), url]
    for h in headers:
        cmd += ['-H', h]
    if data is not None:
        cmd += ['-H', 'Content-Type: application/json', '--data', json.dumps(data)]
    return subprocess.run(cmd, capture_output=True, check=True).stdout


def ok(url):
    r = subprocess.run(['curl', '-s', '-o', '/dev/null', '-r', '0-0', '--max-time', '30', '-w', '%{http_code}', url],
                       capture_output=True, text=True)
    return r.stdout in ('200', '206')


def esc(s):
    s = ' '.join(str(s).split())
    s = s.replace('\\', '\\\\').replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    s = s.replace("'", "\\'").replace('"', '\\"')
    if s[:1] in ('@', '?'):
        s = '\\' + s
    return s


def write(name, comment, arrays):
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- ' + comment + ' -->', '<resources>']
    for key, items in arrays:
        out.append('    <string-array name="%s" translatable="false">' % key)
        out += ['        <item>%s</item>' % esc(i) for i in items]
        out.append('    </string-array>')
    out.append('</resources>\n')
    with open(os.path.join(VALUES, name), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))


# ---------------------------------------------------------------- Apple aerials

def aerials():
    tar = tarfile.open(fileobj=io.BytesIO(fetch('https://sylvan.apple.com/Aerials/resources-16.tar', timeout=300)))
    entries = json.load(tar.extractfile('entries.json'))
    names = {c['id']: c['localizedNameKey'].replace('AerialCategory', '') for c in entries['categories']}
    rows = []
    for a in entries['assets']:
        cat = names.get((a.get('categories') or [''])[0], '')
        if a.get('url-1080-H264'):
            rows.append((cat, a['accessibilityLabel'], a['url-1080-H264'], a.get('url-1080-HDR', '')))
    rows.sort(key=lambda r: (r[0], r[1]))
    write('aerials.xml',
          'Apple TV aerials: landscapes, cities, space and underwater (1080p H.264, plus Dolby Vision for TVs that '
          'can play it), streamed from Apple and cached on the TV. Generated by tools/gen-backgrounds.py.',
          [('aerial_labels', [r[1] for r in rows]), ('aerial_urls', [r[2] for r in rows]),
           ('aerial_urls_hdr', [r[3] for r in rows])])
    counts = {}
    for r in rows:
        counts[r[0]] = counts.get(r[0], 0) + 1
    print('aerials', len(rows), counts)


# ---------------------------------------------------------------- stills

def paintings():
    aic = ['AIC-User-Agent: tvhome (personal TV screensaver)']
    must = [{'term': {'is_public_domain': True}}, {'term': {'artwork_type_title.keyword': 'Painting'}},
            {'exists': {'field': 'image_id'}}]
    fields = ['id', 'title', 'artist_title', 'date_display', 'image_id', 'thumbnail']
    found = {}
    # The museum's highlights first, then other paintings on view, best known first.
    for extra, pages in (([{'term': {'is_boosted': True}}], 2), ([{'term': {'is_on_view': True}}], 4)):
        for page in range(1, pages + 1):
            body = {'query': {'bool': {'must': must + extra}}, 'fields': fields, 'limit': 100, 'page': page,
                    'sort': [{'_score': 'desc'}]}
            for x in json.loads(fetch('https://api.artic.edu/api/v1/artworks/search', body, aic))['data']:
                t = x.get('thumbnail') or {}
                w, h = t.get('width') or 0, t.get('height') or 0
                if not x.get('image_id') or not w or not h or w / h < 0.6:
                    continue  # very tall works leave too little picture on a wide screen
                artist = x.get('artist_title') or 'Unknown artist'
                when = x.get('date_display') or ''
                found[x['id']] = ('art', 'https://www.artic.edu/iiif/2/%s/full/1686,/0/default.jpg' % x['image_id'],
                                  x['title'], artist + (', ' + when if when else '') + ' · Art Institute of Chicago')
    return list(found.values())[:300]


def earth():
    data = json.loads(fetch('https://raw.githubusercontent.com/limhenry/earthview/master/earthview.json'))
    out = []
    for x in data:
        place = ', '.join(p for p in (x.get('region'), x.get('country')) if p)
        if x.get('image') and place:
            out.append(('earth', x['image'], place, 'Google Earth View'))
    return out


def space():
    out, seen = [], set()
    # The library is mostly people, hardware and events; keep only pictures of the sky itself.
    sky = ('nebula', 'galaxy', 'galaxies', 'cluster', 'supernova', 'stellar', 'stars', 'star-forming', 'pillars',
           'cosmic', 'remnant', 'jupiter', 'saturn', 'neptune', 'uranus', 'deep field', 'nursery')
    people = ('team', 'briefing', 'mirror', 'engineer', 'launch', 'chart', 'diagram', 'spectrum', 'town hall',
              'administrator', 'ceremony', 'visit', 'model', 'artist', 'illustration', 'concept', 'graph', 'event')
    for q in ('hubble nebula', 'hubble galaxy', 'hubble star cluster', 'webb nebula', 'webb galaxy',
              'james webb space telescope image'):
        d = json.loads(fetch('https://images-api.nasa.gov/search?media_type=image&page_size=100&q=' + urllib.parse.quote(q)))
        for it in d['collection']['items']:
            meta, links = it['data'][0], it.get('links') or []
            nid = meta['nasa_id']
            title = meta.get('title', '')
            t = title.lower()
            thumb = next((l['href'] for l in links if l.get('rel') == 'preview'), '')
            if nid in seen or not thumb or not any(w in t for w in sky) or any(w in t for w in people):
                continue
            seen.add(nid)
            out.append(('space', thumb.replace('~thumb', '~large'), title, 'NASA'))
    with concurrent.futures.ThreadPoolExecutor(16) as ex:
        good = list(ex.map(lambda r: ok(r[1]), out))
    return [r for r, g in zip(out, good) if g][:200]


def stills():
    art, eth, spc = paintings(), earth(), space()
    rows = art + eth + spc
    write('stills.xml',
          'Still backgrounds shown between aerials: public-domain paintings (Art Institute of Chicago), Google Earth '
          'View, and Hubble / Webb images (NASA). Links and captions only. Generated by tools/gen-backgrounds.py.',
          [('still_kinds', [r[0] for r in rows]), ('still_urls', [r[1] for r in rows]),
           ('still_titles', [r[2] for r in rows]), ('still_credits', [r[3] for r in rows])])
    print('stills: paintings', len(art), 'earth', len(eth), 'space', len(spc))


if __name__ == '__main__':
    aerials()
    stills()
